"""Minimal translation support for Printer Center.

Source strings are English; TR maps them to Turkish. The language comes from the
[client] language setting: "auto" (operating system language), "tr" or "en".

    from i18n import _, N_
    label = _("Scan")            # translated now
    TITLES = [N_("Paper jam")]   # marked for translation, translated later with _(TITLES[0])
"""

import os

LANGUAGES = (("auto", "Automatic (system language)"), ("tr", "Türkçe"), ("en", "English"))
_current = None


def system_language():
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value and value not in ("C", "POSIX", "C.UTF-8"):
            return "tr" if value.lower().startswith("tr") else "en"
    return "en"


def set_language(code="auto"):
    global _current
    _current = code if code in ("tr", "en") else system_language()
    return _current


def language():
    return _current or set_language()


def _(text):
    if language() == "tr":
        return TR.get(text, text)
    return text


def N_(text):
    """Mark a string for translation without translating it yet."""
    return text


